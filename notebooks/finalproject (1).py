def clean_diag(code):
    if code == 'UNKNOWN':
        return 'UNKNOWN'

    # E codes: External causes
    if code.startswith('E'):
        return 'EXTERNAL_CAUSE'

    # V codes: Supplementary factors
    if code.startswith('V'):
        return 'SUPPLEMENTARY'

    # Numeric codes (with or without decimal)
    try:
        code_num = float(code)
    except:
        return 'UNKNOWN'

    if 390 <= code_num < 460:
        return 'CIRCULATORY'
    elif 460 <= code_num < 520:
        return 'RESPIRATORY'
    elif 520 <= code_num < 580:
        return 'DIGESTIVE'
    elif 250 <= code_num < 251:
        return 'DIABETES'
    elif 800 <= code_num < 1000:
        return 'INJURY'
    else:
        return 'OTHER'

